    # Criterion 3
    # Graph Stability
    def _get_topological_stability(
        self,
        candidate: Any,
        base_state: Any
    ) -> float:
        """
        Topological Jaccard similarity.
        """

        base_edges = (
            self._get_edges(
                base_state
            )
        )

        candidate_edges = (
            self._get_edges(
                candidate
            )
        )

        union = (
            base_edges
            |
            candidate_edges
        )

        intersection = (
            base_edges
            &
            candidate_edges
        )

        if not union:
            return 1.0

        return self._clamp(
            len(
                intersection
            )
            /
            len(
                union
            )
        )

    def _get_weight_stability(
        self,
        candidate: Any,
        base_state: Any
    ) -> float:
        """
        Weight similarity for common edges.

        A common edge with identical weight contributes 1.0.
        A common edge with a different weight contributes less.

        Edges present in only one graph are handled by the
        topological stability component rather than being treated
        as a weight comparison.
        """

        base_weights = (
            self._get_weight_map(
                base_state
            )
        )

        candidate_weights = (
            self._get_weight_map(
                candidate
            )
        )

        common_edges = (
            set(
                base_weights
            )
            &
            set(
                candidate_weights
            )
        )

        if not common_edges:
            return 1.0

        similarities = []

        for edge in common_edges:
            base_weight = (
                base_weights[
                    edge
                ]
            )

            candidate_weight = (
                candidate_weights[
                    edge
                ]
            )

            difference = abs(
                base_weight
                -
                candidate_weight
            )

            # Exponential decay keeps the score within [0, 1].
            similarity = (
                1.0
                /
                (
                    1.0
                    +
                    (
                        self.weight_similarity_scale
                        *
                        difference
                    )
                )
            )

            similarities.append(
                self._clamp(
                    similarity
                )
            )

        return self._clamp(
            sum(
                similarities
            )
            /
            len(
                similarities
            )
        )

    def _get_graph_stability(
        self,
        candidate: Any,
        base_state: Any
    ) -> float:
        """
        The final stability score combines:
            70% topology preservation
            30% weight preservation
        """

        topology = (
            self._get_topological_stability(
                candidate,
                base_state
            )
        )

        weight = (
            self._get_weight_stability(
                candidate,
                base_state
            )
        )

        return self._clamp(
            (
                0.70
                *
                topology
            )
            +
            (
                0.30
                *
                weight
            )
        )

    # Criterion 4
    # Parsimony
    def _get_topology_change_count(
        self,
        candidate: Any,
        base_state: Any
    ) -> int:
        """
        Number of added/removed edges.
        """

        base_edges = (
            self._get_edges(
                base_state
            )
        )

        candidate_edges = (
            self._get_edges(
                candidate
            )
        )

        return len(
            base_edges
            ^
            candidate_edges
        )

    def _get_weight_change_count(
        self,
        candidate: Any,
        base_state: Any
    ) -> int:
        """
        Number of edges whose weights changed.
        """

        return len(
            self._infer_weight_change_edges_from_candidate(
                candidate,
                base_state
            )
        )

    def _get_parsimony(
        self,
        candidate: Any,
        base_state: Any
    ) -> float:
        """
        A topological modification counts as one operation.
        A weight modification also counts as one operation.

        Therefore:
            0 modifications -> 1.0
            1 modification  -> 0.5
            2 modifications -> 0.333...
            ...

        This makes weight changes visible to the parsimony
        criterion even when topology is unchanged.
        """

        topology_changes = (
            self._get_topology_change_count(
                candidate,
                base_state
            )
        )

        weight_changes = (
            self._get_weight_change_count(
                candidate,
                base_state
            )
        )

        total_operations = (
            topology_changes
            +
            weight_changes
        )

        return self._clamp(
            1.0
            /
            (
                1.0
                +
                total_operations
            )
        )

    def _get_structural_change_count(
        self,
        candidate: Any,
        base_state: Any
    ) -> int:
        """
        Total number of graph-evolution operations.
        Includes:
            topology changes
            +
            weight changes
        """

        topology_changes = (
            self._get_topology_change_count(
                candidate,
                base_state
            )
        )

        weight_changes = (
            self._get_weight_change_count(
                candidate,
                base_state
            )
        )

        return (
            topology_changes
            +
            weight_changes
        )

    def _calculate_final_score(
        self,
        propagation: float,
        change_consistency: float,
        stability: float,
        parsimony: float
    ) -> float:
        """
        Calculate weighted final ranking score.
        """

        score = (
            self.weight_propagation
            *
            propagation

            +

            self.weight_change_consistency
            *
            change_consistency

            +

            self.weight_stability
            *
            stability

            +

            self.weight_parsimony
            *
            parsimony
        )

        return self._clamp(
            score
        )

    def rank(
        self,
        candidates: List[Any],
        base_state: Any,
        primary_changes: Optional[List[Dict]] = None
    ) -> RankingResult:
        """
        Rank candidate graph evolutions.

        Parameters
        ----------
        candidates:
            Candidate graph states.

        base_state:
            Original stored/base causal graph.

        primary_changes:
            Changes detected by the Change Gate.
        """

        if candidates is None:
            candidates = []

        if primary_changes is None:
            primary_changes = []

        if not candidates:
            return RankingResult(
                ranked_candidates=[],
                top_candidates=[],
                highest_score=None,
                has_tie=False,
                total_candidates=0,
                unique_scores=0,

                weight_propagation=
                    self.weight_propagation,

                weight_change_consistency=
                    self.weight_change_consistency,

                weight_stability=
                    self.weight_stability,

                weight_parsimony=
                    self.weight_parsimony
            )

        scored_candidates = []

        for index, candidate in enumerate(
            candidates,
            start=1
        ):
            propagation = (
                self._get_propagation_plausibility(
                    candidate
                )
            )

            change_consistency = (
                self._get_change_consistency(
                    candidate,
                    base_state,
                    primary_changes
                )
            )

            stability = (
                self._get_graph_stability(
                    candidate,
                    base_state
                )
            )

            parsimony = (
                self._get_parsimony(
                    candidate,
                    base_state
                )
            )

            topology_changes = (
                self._get_topology_change_count(
                    candidate,
                    base_state
                )
            )

            weight_changes = (
                self._get_weight_change_count(
                    candidate,
                    base_state
                )
            )

            structural_changes = (
                topology_changes
                +
                weight_changes
            )

            final_score = (
                self._calculate_final_score(
                    propagation,
                    change_consistency,
                    stability,
                    parsimony
                )
            )

            scored_candidates.append(
                (
                    index,
                    candidate,
                    propagation,
                    change_consistency,
                    stability,
                    parsimony,
                    final_score,
                    structural_changes,
                    topology_changes,
                    weight_changes
                )
            )

        # Sort by final score.
        scored_candidates.sort(
            key=lambda item: item[6],
            reverse=True
        )

        ranked_candidates = []
        previous_score = None
        current_rank = 1
        tie_group = 1

        for position, item in enumerate(
            scored_candidates
        ):
            (
                original_index,
                candidate,
                propagation,
                change_consistency,
                stability,
                parsimony,
                final_score,
                structural_changes,
                topology_changes,
                weight_changes
            ) = item

            if position == 0:
                current_rank = 1
                tie_group = 1

            else:
                scores_equal = (
                    abs(
                        final_score
                        -
                        previous_score
                    )
                    <=
                    self.tie_tolerance
                )

                if not scores_equal:
                    current_rank = (
                        position + 1
                    )

                    tie_group += 1

            ranked = RankedCandidate(
                rank=current_rank,

                candidate_index=
                    original_index,

                candidate_state=
                    candidate,

                propagation_plausibility=
                    propagation,

                change_consistency=
                    change_consistency,

                graph_stability=
                    stability,

                parsimony=
                    parsimony,

                final_score=
                    final_score,

                interaction_plan=
                    self._get_interaction_plan(
                        candidate
                    ),

                interaction_level=
                    self._get_interaction_level(
                        candidate
                    ),

                propagation_rule=
                    self._get_propagation_rule(
                        candidate
                    ),

                structural_changes=
                    structural_changes,

                topology_changes=
                    topology_changes,

                weight_changes=
                    weight_changes,

                is_top_rank=(
                    current_rank == 1
                ),

                tie_group=
                    tie_group
            )

            ranked_candidates.append(
                ranked
            )

            previous_score = (
                final_score
            )

        top_candidates = [
            candidate
            for candidate
            in ranked_candidates
            if candidate.rank == 1
        ]

        has_tie = (
            len(
                top_candidates
            )
            >
            1
        )

        # Unique score levels
        unique_scores = []

        for item in scored_candidates:
            score = item[6]

            if not any(
                abs(
                    score
                    -
                    existing
                )
                <=
                self.tie_tolerance

                for existing
                in unique_scores
            ):
                unique_scores.append(
                    score
                )

        return RankingResult(
            ranked_candidates=
                ranked_candidates,

            top_candidates=
                top_candidates,

            highest_score=
                ranked_candidates[0].final_score,

            has_tie=
                has_tie,

            total_candidates=
                len(candidates),

            unique_scores=
                len(unique_scores),

            weight_propagation=
                self.weight_propagation,

            weight_change_consistency=
                self.weight_change_consistency,

            weight_stability=
                self.weight_stability,

            weight_parsimony=
                self.weight_parsimony
        )

