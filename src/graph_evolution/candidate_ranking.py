"""
Candidate Graph Ranking Engine
==============================

Ranks candidate causal graph evolutions generated by the
GraphEvolutionEngine.

Ranking criteria
1. Propagation Plausibility
2. Change Consistency
3. Graph Stability
4. Parsimony

Current default weights:
    Propagation Plausibility : 0.40
    Change Consistency       : 0.30
    Graph Stability          : 0.20
    Parsimony                : 0.10

Important
---------
This module ranks candidate GRAPH EVOLUTIONS.

A candidate graph is not a replacement for the stored/base graph.

The ranking engine never mutates the base graph.

The eventual graph-update stage will apply the selected evolution
to the existing base graph.
"""


from dataclasses import dataclass
from pathlib import Path
from typing import Any, Dict, List, Optional, Tuple

from openpyxl import Workbook
from openpyxl.styles import Font

@dataclass
class RankedCandidate:
    """
    Stores one candidate together with all ranking components.
    """

    rank: int
    candidate_index: int
    candidate_state: Any
    propagation_plausibility: float
    change_consistency: float
    graph_stability: float
    parsimony: float
    final_score: float
    interaction_plan: str
    interaction_level: int
    propagation_rule: str
    structural_changes: int
    topology_changes: int
    weight_changes: int
    is_top_rank: bool = False
    tie_group: Optional[int] = None


@dataclass
class RankingResult:

    ranked_candidates: List[RankedCandidate]
    top_candidates: List[RankedCandidate]
    highest_score: Optional[float]
    has_tie: bool
    total_candidates: int
    unique_scores: int
    weight_propagation: float
    weight_change_consistency: float
    weight_stability: float
    weight_parsimony: float
    ranking_method: str = (
        "Weighted multi-criteria candidate graph evolution ranking"
    )

    def summary(self) -> Dict:
        return {
            "TotalCandidates":
                self.total_candidates,

            "HighestFinalScore":
                self.highest_score,

            "TopCandidateCount":
                len(
                    self.top_candidates
                ),

            "HasTopRankTie":
                self.has_tie,

            "PropagationWeight":
                self.weight_propagation,

            "ChangeConsistencyWeight":
                self.weight_change_consistency,

            "StabilityWeight":
                self.weight_stability,

            "ParsimonyWeight":
                self.weight_parsimony,

            "RankingMethod":
                self.ranking_method
        }

class CandidateRankingEngine:
    """
    Ranks candidate graph evolutions.

    The ranking is based on four criteria:
        Propagation Plausibility
        Change Consistency
        Graph Stability
        Parsimony

    The engine does not mutate graphs.
    """

    SCORE_ATTRIBUTE = (
        "candidate_probability"
    )

    def __init__(
        self,
        weight_propagation: float = 0.40,
        weight_change_consistency: float = 0.30,
        weight_stability: float = 0.20,
        weight_parsimony: float = 0.10,
        tie_tolerance: float = 1e-9,
        weight_similarity_scale: float = 1.0
    ):
        """
        Parameters
        ----------
        weight_similarity_scale :
            Controls how quickly edge-weight differences reduce
            the weight-similarity component.

            1.0 means a difference of 1.0 in normalized edge
            weight contributes fully to the distance.
        """

        total_weight = (
            weight_propagation
            +
            weight_change_consistency
            +
            weight_stability
            +
            weight_parsimony
        )

        if total_weight <= 0:
            raise ValueError(
                "Ranking weights must have a positive sum."
            )

        self.weight_propagation = (
            weight_propagation
            /
            total_weight
        )

        self.weight_change_consistency = (
            weight_change_consistency
            /
            total_weight
        )

        self.weight_stability = (
            weight_stability
            /
            total_weight
        )

        self.weight_parsimony = (
            weight_parsimony
            /
            total_weight
        )

        self.tie_tolerance = (
            tie_tolerance
        )

        self.weight_similarity_scale = (
            weight_similarity_scale
        )

    @staticmethod
    def _safe_float(
        value: Any,
        default: float = 0.0
    ) -> float:
        """
        Safely convert a value to float.
        """

        try:
            return float(
                value
            )

        except (
            TypeError,
            ValueError
        ):
            return default

    @staticmethod
    def _clamp(
        value: float,
        minimum: float = 0.0,
        maximum: float = 1.0
    ) -> float:
        """
        Clamp a value.
        """

        return max(
            minimum,
            min(
                maximum,
                value
            )
        )

    def _get_graph(
        self,
        state: Any
    ):
        """
        Extract a NetworkX graph from a causal state.
        """

        if state is None:
            return None

        # Direct NetworkX graph.
        if (
            hasattr(
                state,
                "nodes"
            )
            and
            hasattr(
                state,
                "edges"
            )
        ):
            return state

        # CausalState.graph
        graph = getattr(
            state,
            "graph",
            None
        )

        if graph is not None:
            return graph

        # CausalState.causal_graph
        graph = getattr(
            state,
            "causal_graph",
            None
        )

        if graph is not None:
            return graph

        return None

    def _get_edges(
        self,
        state: Any
    ) -> set:
        """
        Return directed edge set.
        """

        graph = self._get_graph(
            state
        )

        if graph is None:
            return set()

        try:
            return {
                (
                    source,
                    target
                )
                for source, target
                in graph.edges()
            }

        except Exception:
            return set()

    def _get_nodes(
        self,
        state: Any
    ) -> set:
        """
        Return graph nodes.
        """

        graph = self._get_graph(
            state
        )

        if graph is None:
            return set()

        try:
            return set(
                graph.nodes()
            )

        except Exception:
            return set()

    def _get_edge_weight(
        self,
        graph: Any,
        edge: Tuple
    ) -> float:
        """
        Extract an edge weight.

        If the edge has no explicit weight, 1.0 is used.

        This keeps topology-only graphs compatible with the
        weight-aware stability calculation.
        """

        if graph is None:
            return 1.0

        try:
            data = graph.get_edge_data(
                edge[0],
                edge[1],
                default={}
            )

        except Exception:
            return 1.0

        if not isinstance(
            data,
            dict
        ):
            return 1.0

        weight = data.get(
            "weight",
            1.0
        )

        return self._safe_float(
            weight,
            default=1.0
        )

    def _get_weight_map(
        self,
        state: Any
    ) -> Dict[Tuple, float]:
        """
        Return:
            edge -> weight

        for all edges in a graph.
        """

        graph = self._get_graph(
            state
        )

        if graph is None:
            return {}

        weight_map = {}

        try:
            edges = graph.edges()
            for source, target in edges:
                edge = (
                    source,
                    target
                )

                weight_map[edge] = (
                    self._get_edge_weight(
                        graph,
                        edge
                    )
                )

        except Exception:
            return {}

        return weight_map

    def _normalize_primary_change(
        self,
        change: Any
    ) -> Dict:
        """
        Normalize a primary change representation.
        """

        if isinstance(
            change,
            dict
        ):
            return change

        result = {}

        change_type = getattr(
            change,
            "type",
            None
        )

        edge = getattr(
            change,
            "edge",
            None
        )

        node = getattr(
            change,
            "node",
            None
        )

        weight = getattr(
            change,
            "weight",
            None
        )

        old_weight = getattr(
            change,
            "old_weight",
            None
        )

        new_weight = getattr(
            change,
            "new_weight",
            None
        )

        if change_type is not None:
            result["type"] = (
                change_type
            )

        if edge is not None:
            result["edge"] = (
                edge
            )

        if node is not None:
            result["node"] = (
                node
            )

        if weight is not None:
            result["weight"] = (
                weight
            )

        if old_weight is not None:
            result["old_weight"] = (
                old_weight
            )

        if new_weight is not None:
            result["new_weight"] = (
                new_weight
            )

        return result

    def _get_change_type(
        self,
        change: Dict
    ) -> str:
        """
        Normalize change type.
        """

        return str(
            change.get(
                "type",
                ""
            )
        ).upper()

    def _get_change_edge(
        self,
        change: Dict
    ) -> Optional[Tuple]:
        """
        Extract an edge from a primary change.
        """

        edge = change.get(
            "edge"
        )

        if edge is None:
            return None

        try:
            source, target = edge

            return (
                source,
                target
            )

        except (
            TypeError,
            ValueError
        ):
            return None

    # Criterion 1
    # Propagation Plausibility
    def _get_propagation_plausibility(
        self,
        candidate: Any
    ) -> float:

        score = getattr(
            candidate,
            self.SCORE_ATTRIBUTE,
            None
        )

        if score is None:
            score = getattr(
                candidate,
                "plausibility_score",
                None
            )

        return self._clamp(
            self._safe_float(
                score,
                default=0.0
            )
        )

    def _get_notes(
        self,
        candidate: Any
    ) -> Dict:
        """
        Extract candidate notes.
        """

        notes = getattr(
            candidate,
            "notes",
            {}
        )

        if not isinstance(
            notes,
            dict
        ):
            return {}

        return notes

    def _get_interaction_plan(
        self,
        candidate: Any
    ) -> str:
        """
        Extract interaction plan.
        """

        notes = self._get_notes(
            candidate
        )

        return str(
            notes.get(
                "InteractionPlan",
                notes.get(
                    "EvolutionOperator",
                    "Unknown"
                )
            )
        )

    def _get_interaction_level(
        self,
        candidate: Any
    ) -> int:
        """
        Extract interaction level.
        """

        notes = self._get_notes(
            candidate
        )

        value = notes.get(
            "InteractionLevel",
            0
        )

        try:
            return int(
                value
            )

        except (
            TypeError,
            ValueError
        ):
            return 0

    def _get_propagation_rule(
        self,
        candidate: Any
    ) -> str:
        """
        Extract propagation rule.
        """

        notes = self._get_notes(
            candidate
        )

        return str(
            notes.get(
                "PropagationRule",
                "Unknown"
            )
        )

    def _get_evolution_text(
        self,
        candidate: Any
    ) -> str:
        """
        Return a combined lower-case textual description of
        the candidate evolution.

        This is used only as a fallback when explicit metadata
        is unavailable.
        """

        notes = self._get_notes(
            candidate
        )

        values = []

        for key in (
            "InteractionPlan",
            "EvolutionOperator",
            "PropagationRule"
        ):

            value = notes.get(
                key
            )

            if value is not None:
                values.append(
                    str(value)
                )

        return " ".join(
            values
        ).lower()

    def _weight_changed_edges_from_primary_changes(
        self,
        primary_changes: List[Dict]
    ) -> set:
        """
        Extract edges explicitly identified by the Change Gate as
        weight-changed edges.
        """

        result = set()

        for raw_change in primary_changes:
            change = (
                self._normalize_primary_change(
                    raw_change
                )
            )

            change_type = (
                self._get_change_type(
                    change
                )
            )

            if change_type not in {
                "WEIGHT_CHANGE",
                "WEIGHT_CHANGED",
                "WEIGHT_CHANGED_EDGE"
            }:
                continue

            edge = (
                self._get_change_edge(
                    change
                )
            )

            if edge is not None:
                result.add(
                    edge
                )

        return result

    def _infer_weight_change_edges_from_candidate(
        self,
        candidate: Any,
        base_state: Any
    ) -> set:
        """
        Detect edge-weight differences between the base and candidate
        graphs.

        This catches weight modifications even when the topology is
        unchanged.
        """

        base_weights = (
            self._get_weight_map(
                base_state
            )
        )

        candidate_weights = (
            self._get_weight_map(
                candidate
            )
        )

        common_edges = (
            set(
                base_weights
            )
            &
            set(
                candidate_weights
            )
        )

        changed_edges = set()

        for edge in common_edges:
            base_weight = (
                base_weights[
                    edge
                ]
            )

            candidate_weight = (
                candidate_weights[
                    edge
                ]
            )

            if abs(
                base_weight
                -
                candidate_weight
            ) > 1e-9:
                changed_edges.add(
                    edge
                )

        return changed_edges

    # Criterion 2
    # Change Consistency
    def _change_is_satisfied(
        self,
        change: Dict,
        candidate: Any,
        base_state: Any
    ) -> bool:

        change_type = (
            self._get_change_type(
                change
            )
        )

        edge = (
            self._get_change_edge(
                change
            )
        )

        base_edges = (
            self._get_edges(
                base_state
            )
        )

        candidate_edges = (
            self._get_edges(
                candidate
            )
        )

        # EDGE ADDITION
        if change_type in {
            "EDGE_ADDITION",
            "ADDED_EDGE"
        }:

            if edge is None:
                return False

            return (
                edge not in base_edges
                and
                edge in candidate_edges
            )

        # EDGE REMOVAL
        if change_type in {
            "EDGE_REMOVAL",
            "REMOVED_EDGE"
        }:

            if edge is None:
                return False

            return (
                edge in base_edges
                and
                edge not in candidate_edges
            )

        # WEIGHT CHANGE
        if change_type in {
            "WEIGHT_CHANGE",
            "WEIGHT_CHANGED",
            "WEIGHT_CHANGED_EDGE"
        }:

            if edge is None:
                return False

            base_weights = (
                self._get_weight_map(
                    base_state
                )
            )

            candidate_weights = (
                self._get_weight_map(
                    candidate
                )
            )

            if edge not in base_weights:
                return False

            if edge not in candidate_weights:
                return False

            return (
                abs(
                    base_weights[edge]
                    -
                    candidate_weights[edge]
                )
                >
                1e-9
            )

        # ISOLATED NODE
        if change_type in {
            "ISOLATED_NODE",
            "ISOLATION",
            "NODE_ISOLATION"
        }:

            node = change.get(
                "node"
            )

            if node is None:
                return False

            base_edges_for_node = [
                edge
                for edge
                in base_edges
                if (
                    edge[0] == node
                    or
                    edge[1] == node
                )
            ]

            candidate_edges_for_node = [
                edge
                for edge
                in candidate_edges
                if (
                    edge[0] == node
                    or
                    edge[1] == node
                )
            ]

            # The candidate should introduce connectivity
            # for the affected node.
            return (
                len(
                    candidate_edges_for_node
                )
                >
                len(
                    base_edges_for_node
                )
            )

        return False


    def _get_change_consistency(
        self,
        candidate: Any,
        base_state: Any,
        primary_changes: Optional[List[Dict]]
    ) -> float:
        """
        Measure how consistently a candidate graph implements the
        detected primary changes.

        Each primary change is evaluated independently.

        A candidate receives credit only when the corresponding
        structural
        change is actually represented in the candidate graph.

        The final score is:

            Change Consistency =
                satisfied_primary_changes
                /
                total_primary_changes

        Therefore:

            all changes satisfied -> 1.0
            3 / 4 satisfied       -> 0.75
            2 / 4 satisfied       -> 0.50
            1 / 4 satisfied       -> 0.25
            0 / 4 satisfied       -> 0.00

        This deliberately evaluates the actual identity of each
        primary change rather than merely counting the number of
        structural operations performed by the candidate.
        """

        if not primary_changes:

            return 1.0

        base_graph = (
            base_state.graph
        )

        candidate_graph = (
            candidate.graph
        )

        satisfied_changes = 0

        total_changes = len(
            primary_changes
        )

        for change in primary_changes:

            if not isinstance(
                change,
                dict
            ):

                continue

            change_type = (
                change.get(
                    "type"
                )
            )

            # ======================================================
            # EDGE ADDITION
            # ======================================================

            if change_type == "EDGE_ADDITION":

                edge = (
                    change.get(
                        "edge"
                    )
                )

                if (
                    edge is not None
                    and
                    candidate_graph.has_edge(
                        edge[0],
                        edge[1]
                    )
                    and
                    not base_graph.has_edge(
                        edge[0],
                        edge[1]
                    )
                ):

                    satisfied_changes += 1

            # ======================================================
            # EDGE REMOVAL
            # ======================================================

            elif change_type == "EDGE_REMOVAL":

                edge = (
                    change.get(
                        "edge"
                    )
                )

                if (
                    edge is not None
                    and
                    base_graph.has_edge(
                        edge[0],
                        edge[1]
                    )
                    and
                    not candidate_graph.has_edge(
                        edge[0],
                        edge[1]
                    )
                ):

                    satisfied_changes += 1

            # ======================================================
            # WEIGHT CHANGE
            # ======================================================

            elif change_type in (
                "WEIGHT_CHANGE",
                "WEIGHT_CHANGED"
            ):

                edge = (
                    change.get(
                        "edge"
                    )
                )

                if (
                    edge is None
                    or
                    not base_graph.has_edge(
                        edge[0],
                        edge[1]
                    )
                    or
                    not candidate_graph.has_edge(
                        edge[0],
                        edge[1]
                    )
                ):

                    continue

                old_weight = (
                    change.get(
                        "old_weight"
                    )
                )

                new_weight = (
                    change.get(
                        "new_weight"
                    )
                )

                candidate_old_weight = (
                    base_graph[
                        edge[0]
                    ][
                        edge[1]
                    ].get(
                        "weight"
                    )
                )

                candidate_new_weight = (
                    candidate_graph[
                        edge[0]
                    ][
                        edge[1]
                    ].get(
                        "weight"
                    )
                )

                old_matches = (
                    self._weights_equal(
                        candidate_old_weight,
                        old_weight
                    )
                )

                new_matches = (
                    self._weights_equal(
                        candidate_new_weight,
                        new_weight
                    )
                )

                if (
                    old_matches
                    and
                    new_matches
                ):

                    satisfied_changes += 1

            # ======================================================
            # ISOLATED NODE
            # ======================================================

            elif change_type == "ISOLATED_NODE":

                node = (
                    change.get(
                        "node"
                    )
                )

                if node is None:

                    continue

                # The primary change says that this node became
                # isolated in the newly observed/current state.
                #
                # A candidate consistently implementing that change
                # should preserve the node's isolated state unless
                # the candidate explicitly proposes a recovery
                # action for that node.
                #
                # Therefore:
                #
                #     Base graph connected
                #     Candidate graph isolated
                #
                # is considered a direct implementation of the
                # detected isolation change.

                base_degree = (
                    base_graph.degree(
                        node
                    )
                    if node in base_graph
                    else 0
                )

                candidate_degree = (
                    candidate_graph.degree(
                        node
                    )
                    if node in candidate_graph
                    else 0
                )

                if (
                    base_degree > 0
                    and
                    candidate_degree == 0
                ):

                    satisfied_changes += 1

            # ======================================================
            # UNKNOWN CHANGE TYPE
            # ======================================================

            else:

                continue

        return (
            satisfied_changes
            /
            total_changes
        )
